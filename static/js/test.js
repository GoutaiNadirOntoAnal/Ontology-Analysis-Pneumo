$(document).ready(function() {
  // Add an event listener to the checkbox
  $("#tabac-checkbox").change(function() {
    // Check if the checkbox is checked
    if ($(this).is(":checked")) {
      // Show the tabac-radio-div if checked
      $("#tabac-radio-div").show();
    } else {
      // Hide the tabac-radio-div if unchecked
      $("#tabac-radio-div").hide();
    }
  });
});

